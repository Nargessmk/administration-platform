    {
        try
        {
            var result = await _mediator.Send(new GetBedViewsByRoomIdPagingQuery(roomId, pageNumber, pageSize));
            return Ok(result);
        }
        catch (Exception ex)
        {
            return BadRequest(new { message = ex.Message });
        }
    }
    
}
