    }

    [HttpGet("View/Contractor/{contractorId:guid}")]
    [ProducesResponseType(typeof(ResultDTO<List<ContractViewDTO>>), (int)HttpStatusCode.OK)]
    [ProducesResponseType((int)HttpStatusCode.BadRequest)]
